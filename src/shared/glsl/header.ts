// Generated GLSL constants (§3). The single source of truth is contracts.ts; never hand-copy numbers into GLSL.
import {
  AnimKind, AT, CANVAS_ASPECT, CLASS_COUNT, CLASS_INFO, FLAG_STRIDE, JET_CTRL, JET_D0, JET_D1, LAYIN_CENTER, LOOP_SECONDS,
  MOON_DEF, MOON_INDEX, MOON_RING_D, MOON_RING_RHO, PALETTE, STAR_RING_D, STAR_RING_RHO, STARS, StrokeClass, StrokeFlag,
  T_HALF, VORTICES, SKY_GEN_U, SKY_GEN_V, SKY_EDGE_FADE, type PaletteKey,
} from '../../contracts';
import { srgbHexToLinear } from '../palette';
import { MOON_HALO_R, starHaloSigned } from '../flowField';

/** GLSL float literal. */
export function f(x: number): string {
  if (!Number.isFinite(x)) throw new Error(`non-finite GLSL constant ${x}`);
  if (Number.isInteger(x)) return `${x}.0`;
  const s = String(x);
  return s.includes('.') || s.includes('e') ? s : `${s}.0`;
}
const v2 = (a: number, b: number) => `vec2(${f(a)}, ${f(b)})`;
const v3 = (a: readonly number[]) => `vec3(${f(a[0])}, ${f(a[1])}, ${f(a[2])})`;
const v4 = (a: number, b: number, c: number, d: number) => `vec4(${f(a)}, ${f(b)}, ${f(c)}, ${f(d)})`;
const arr = (type: string, items: string[]) => `${type}[${items.length}](\n  ${items.join(',\n  ')})`;
const snake = (k: string) => k.replace(/([A-Z])/g, '_$1').toUpperCase();

const classes = Array.from({ length: CLASS_COUNT }, (_, i) => CLASS_INFO[i as StrokeClass]);

const lines: string[] = [];
lines.push('// ---------- generated by header.ts: do not edit ----------');
lines.push(`#define CANVAS_ASPECT ${f(CANVAS_ASPECT)}`);
lines.push(`#define AT ${f(AT)}`);
lines.push(`#define T_HALF ${f(T_HALF)}`);
lines.push(`#define SN_PI 3.141592653589793`);
lines.push(`#define SN_TAU 6.283185307179586`);
lines.push(`#define N_VORT ${VORTICES.length}`);
lines.push(`#define N_STAR ${STARS.length}`);
lines.push(`#define MOON_INDEX ${MOON_INDEX}`);
lines.push(`#define CLASS_COUNT ${CLASS_COUNT}`);
lines.push(`#define LOOP_SECONDS ${f(LOOP_SECONDS)}`);
lines.push(`#define FLAG_STRIDE ${f(FLAG_STRIDE)}`);
lines.push(`#define FLAG_UNDERLAYER ${StrokeFlag.UNDERLAYER}`);
lines.push(`#define FLAG_OUTLINE ${StrokeFlag.OUTLINE}`);
for (const [name, value] of Object.entries(StrokeClass)) {
  if (typeof value === 'number') lines.push(`#define CLS_${name} ${value}`);
}
for (const [name, value] of Object.entries(AnimKind)) {
  if (typeof value === 'number') lines.push(`#define ANIM_${name} ${value}`);
}
lines.push(`#define LAYIN_CENTER ${v2(LAYIN_CENTER[0], LAYIN_CENTER[1])}`);
lines.push(`#define STAR_RING_RHO ${f(STAR_RING_RHO)}`);
lines.push(`#define STAR_RING_D ${f(STAR_RING_D)}`);
lines.push(`#define MOON_RING_RHO ${f(MOON_RING_RHO)}`);
lines.push(`#define MOON_RING_D ${f(MOON_RING_D)}`);
lines.push(`#define JET_D0 ${f(JET_D0)}`);
lines.push(`#define JET_D1 ${f(JET_D1)}`);
lines.push(`#define SKY_GEN_EXT vec4(${f(SKY_GEN_U[0])}, ${f(SKY_GEN_V[0])}, ${f(SKY_GEN_U[1])}, ${f(SKY_GEN_V[1])})  // (uMin, vMin, uMax, vMax)`);
lines.push(`#define SKY_EDGE_FADE ${f(SKY_EDGE_FADE)}`);

lines.push('// VORT[i] = (cx = u*A, cy, gamma (+CCW), rc)');
lines.push(`const vec4 VORT[${VORTICES.length}] = ${arr('vec4', VORTICES.map((V) => v4(V.u * CANVAS_ASPECT, V.v, V.gamma, V.rc)))};`);
lines.push('// VORT_W[i] = (window sigma, sink beta)');
lines.push(`const vec2 VORT_W[${VORTICES.length}] = ${arr('vec2', VORTICES.map((V) => v2(V.sigma, V.beta)))};`);
lines.push('// VORT_GEO[i] = (r0, rmax, dThroat (m), depthExpo)');
lines.push(`const vec4 VORT_GEO[${VORTICES.length}] = ${arr('vec4', VORTICES.map((V) => v4(V.r0, V.rmax, V.dThroat, V.expo)))};`);
lines.push('// STAR[k] = (cx, cy, rhoCore, signedHaloR)  sign = circulation direction');
lines.push(`const vec4 STAR[${STARS.length}] = ${arr('vec4', STARS.map((s, i) => v4(s.u * CANVAS_ASPECT, s.v, s.rhoCore, starHaloSigned(i))))};`);
lines.push('// STAR_D[k] = (dCore, ringCount, 0, 0)');
lines.push(`const vec4 STAR_D[${STARS.length}] = ${arr('vec4', STARS.map((s) => v4(s.dCore, s.rings, 0, 0)))};`);
lines.push('// MOON = (cx, cy, rCrescent, haloR); MOON_D = (d, rings, 0, 0)');
lines.push(`const vec4 MOON = ${v4(MOON_DEF.u * CANVAS_ASPECT, MOON_DEF.v, MOON_DEF.rCrescent, MOON_HALO_R)};`);
lines.push(`const vec4 MOON_D = ${v4(MOON_DEF.d, MOON_DEF.rings, 0, 0)};`);
lines.push(`const vec2 JET_CTRL[4] = ${arr('vec2', JET_CTRL.map((c) => v2(c[0], c[1])))};`);
lines.push(`const int ANIM_KIND[${CLASS_COUNT}] = int[${CLASS_COUNT}](${classes.map((c) => String(c.anim)).join(', ')});`);
lines.push(`const float OUTLINE_W[${CLASS_COUNT}] = float[${CLASS_COUNT}](${classes.map((c) => f(c.outline)).join(', ')});`);
lines.push(`const float CLASS_SKY[${CLASS_COUNT}] = float[${CLASS_COUNT}](${classes.map((c) => (c.sky ? '1.0' : '0.0')).join(', ')});`);
lines.push(`const float CLASS_SOLID[${CLASS_COUNT}] = float[${CLASS_COUNT}](${classes.map((c) => (c.solid ? '1.0' : '0.0')).join(', ')});`);
lines.push('// palette, linear RGB');
for (const k of Object.keys(PALETTE) as PaletteKey[]) {
  lines.push(`const vec3 PAL_${snake(k)} = ${v3(srgbHexToLinear(PALETTE[k]))};`);
}
lines.push('// ---------------------------------------------------------');

export const GLSL_HEADER = lines.join('\n') + '\n';
